"""Trim each title image to its ink (+0.3 em), symmetric about the centre, and
rescale its manifest width.  h2 boxes span the container, so the raw crops
carried empty margins that made max-width:100% shrink the lettering early.

usage: python3 trim.py <titles dir>
"""
import json, os, re, sys
import numpy as np
from PIL import Image

D = sys.argv[1]
js = open(os.path.join(D, 'titles.js')).read()
M = json.loads(re.search(r'window\.CHARCOAL_TITLES = (.*);', js).group(1))
for name, themes in M.items():
    for theme, layouts in themes.items():
        for layout, d in layouts.items():
            p = os.path.join(D, f'{name}-{theme}-{layout}.webp')
            im = Image.open(p); a = np.asarray(im)[..., 3]
            w = im.width
            px_per_em = w / d['w']
            cols = np.where((a > 128).sum(axis=0) > 0)[0]          # columns with solid ink
            half = max(cols.max() - w / 2, w / 2 - cols.min()) + 0.3 * px_per_em
            x0 = max(0, int(round(w / 2 - half))); x1 = min(w, int(round(w / 2 + half)))
            if x1 - x0 < w:
                out = im.crop((x0, 0, x1, im.height))
                # re-feather the new side edges (the old feather was cropped away)
                arr = np.asarray(out).copy(); f = max(8, int(out.width * 0.04))
                ramp = np.clip(np.minimum(np.arange(out.width), np.arange(out.width)[::-1]) / f, 0, 1)
                arr[..., 3] = (arr[..., 3] * (ramp * ramp * (3 - 2 * ramp))[None, :]).astype(np.uint8)
                Image.fromarray(arr, 'RGBA').save(p, 'WEBP', quality=80, method=6)
                d['w'] = round(d['w'] * (x1 - x0) / w, 4)
            print(name, theme, layout, w, '->', x1 - x0, 'w', d['w'], os.path.getsize(p) // 1024, 'KB')
open(os.path.join(D, 'titles.js'), 'w').write(
    "/* generated by the charcoal title build: width and dust padding in em of each title's font */\n"
    'window.CHARCOAL_TITLES = ' + json.dumps(M, separators=(',', ':')) + ';\n')
